/**
 * 按区域写入 Android 壳名称 / appId 相关字符串
 * usage: node scripts/apply-capacitor-region.mjs cn|intl
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const region = (process.argv[2] || "cn").toLowerCase();
const isIntl = region === "intl" || region === "international";

const profile = isIntl
  ? {
      appId: "app.serein.day",
      appName: "Serein",
      background: "#f4f7f8",
    }
  : {
      appId: "app.serein.cn",
      appName: "Serein 静澄",
      background: "#f5f2ec",
    };

// 1) 覆盖运行时 capacitor.config 源（下次 cap 读取）
const capTs = `import type { CapacitorConfig } from "@capacitor/cli";

/** Auto-generated by apply-capacitor-region.mjs — region=${isIntl ? "intl" : "cn"} */
const config: CapacitorConfig = {
  appId: "${profile.appId}",
  appName: "${profile.appName}",
  webDir: "dist",
  server: { androidScheme: "https" },
  android: {
    allowMixedContent: false,
    backgroundColor: "${profile.background}",
  },
  plugins: {
    SplashScreen: {
      launchShowDuration: 1200,
      backgroundColor: "${profile.background}",
      showSpinner: false,
    },
  },
};

export default config;
`;
fs.writeFileSync(path.join(root, "capacitor.config.ts"), capTs, "utf8");

// 2) Android strings
const stringsPath = path.join(
  root,
  "android/app/src/main/res/values/strings.xml",
);
if (fs.existsSync(stringsPath)) {
  let xml = fs.readFileSync(stringsPath, "utf8");
  xml = xml.replace(
    /<string name="app_name">[^<]*<\/string>/,
    `<string name="app_name">${profile.appName}</string>`,
  );
  xml = xml.replace(
    /<string name="title_activity_main">[^<]*<\/string>/,
    `<string name="title_activity_main">${profile.appName}</string>`,
  );
  xml = xml.replace(
    /<string name="package_name">[^<]*<\/string>/,
    `<string name="package_name">${profile.appId}</string>`,
  );
  xml = xml.replace(
    /<string name="custom_url_scheme">[^<]*<\/string>/,
    `<string name="custom_url_scheme">${profile.appId}</string>`,
  );
  fs.writeFileSync(stringsPath, xml, "utf8");
}

// 3) Android applicationId only（namespace 保持 Java 包路径，避免改目录）
const gradlePath = path.join(root, "android/app/build.gradle");
if (fs.existsSync(gradlePath)) {
  let g = fs.readFileSync(gradlePath, "utf8");
  g = g.replace(
    /applicationId\s+"[^"]+"/,
    `applicationId "${profile.appId}"`,
  );
  // 不改 namespace：与 src/main/java 包一致即可
  fs.writeFileSync(gradlePath, g, "utf8");
}

// 4) Write capacitor.config.json into android assets if present
const capJson = {
  appId: profile.appId,
  appName: profile.appName,
  webDir: "dist",
  server: { androidScheme: "https" },
  android: {
    allowMixedContent: false,
    backgroundColor: profile.background,
  },
  plugins: {
    SplashScreen: {
      launchShowDuration: 1200,
      backgroundColor: profile.background,
      showSpinner: false,
    },
  },
};
const jsonTargets = [
  path.join(root, "android/app/src/main/assets/capacitor.config.json"),
];
for (const t of jsonTargets) {
  if (fs.existsSync(path.dirname(t))) {
    fs.writeFileSync(t, JSON.stringify(capJson, null, "\t") + "\n", "utf8");
  }
}

console.log(
  `[serein] region=${isIntl ? "intl" : "cn"} appId=${profile.appId} name=${profile.appName}`,
);
